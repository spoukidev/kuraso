const LANG_STORAGE_KEY = "kuraso:ui-language:v1";

export function getLanguageDirection(lang) {
  return lang === "ar" ? "rtl" : "ltr";
}

export function loadUILanguage() {
  try {
    const val = globalThis.localStorage?.getItem(LANG_STORAGE_KEY);
    if (val === "fr" || val === "en" || val === "ar") return val;
  } catch {
    // Ignore.
  }
  return "en";
}

export function saveUILanguage(lang) {
  try {
    globalThis.localStorage?.setItem(LANG_STORAGE_KEY, lang);
  } catch {
    // Ignore.
  }
}

